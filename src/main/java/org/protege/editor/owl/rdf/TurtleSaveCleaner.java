package org.protege.editor.owl.rdf;

import java.io.File;
import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;

class TurtleSaveCleaner {
	private static final String GENERATED_BY_OWLAPI = "Generated by the OWL API";
	
	void clean(URI physicalURI) throws IOException {
		if (physicalURI == null || !"file".equalsIgnoreCase(physicalURI.getScheme())) {
			return;
		}
		File file = new File(physicalURI);
		if (!isTurtleLike(file) || !file.isFile()) {
			return;
		}
		List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
		if (!containsOwlApiGeneratedComment(lines)) {
			return;
		}
		List<String> cleanedLines = new ArrayList<String>();
		for (String line : lines) {
			if (!isGeneratedCommentLine(line)) {
				cleanedLines.add(line);
			}
		}
		Files.write(file.toPath(), cleanedLines, StandardCharsets.UTF_8);
	}
	
	private boolean isTurtleLike(File file) {
		String name = file.getName().toLowerCase();
		return name.endsWith(".ttl") || name.endsWith(".owl") || name.endsWith(".rdf");
	}
	
	private boolean containsOwlApiGeneratedComment(List<String> lines) {
		for (String line : lines) {
			if (line.contains(GENERATED_BY_OWLAPI)) {
				return true;
			}
		}
		return false;
	}
	
	private boolean isGeneratedCommentLine(String line) {
		String trimmed = line.trim();
		if (!trimmed.startsWith("#")) {
			return false;
		}
		String comment = trimmed.substring(1).trim();
		return comment.length() == 0
				|| comment.startsWith("#")
				|| comment.startsWith("###")
				|| comment.matches("#+")
				|| comment.equals("Classes")
				|| comment.equals("Object Properties")
				|| comment.equals("Data properties")
				|| comment.equals("Data Properties")
				|| comment.equals("Annotation properties")
				|| comment.equals("Annotation Properties")
				|| comment.equals("Individuals")
				|| comment.equals("Annotations")
				|| comment.startsWith(GENERATED_BY_OWLAPI)
				|| comment.matches("<?https?://[^\\s>]+>?")
				|| comment.matches("<?urn:[^\\s>]+>?");
	}
}
