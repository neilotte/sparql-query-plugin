package org.protege.editor.owl.rdf;

import java.io.File;
import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

class TurtleSaveCleaner {
	private static final String GENERATED_BY_OWLAPI = "Generated by the OWL API";
	private final Set<String> objectPropertyIRIs = new HashSet<String>();
	private final Set<String> namedIndividualIRIs = new HashSet<String>();
	
	void addCleanupPlan(SparqlUpdateCleanupPlan cleanupPlan) {
		objectPropertyIRIs.addAll(cleanupPlan.getObjectPropertyIRIs());
		namedIndividualIRIs.addAll(cleanupPlan.getNamedIndividualIRIs());
	}
	
	void clean(URI physicalURI) throws IOException {
		if (physicalURI == null || !"file".equalsIgnoreCase(physicalURI.getScheme())) {
			return;
		}
		File file = new File(physicalURI);
		if (!isTurtleLike(file) || !file.isFile()) {
			return;
		}
		List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
		if (!containsOwlApiGeneratedComment(lines) && objectPropertyIRIs.isEmpty() && namedIndividualIRIs.isEmpty()) {
			return;
		}
		List<String> cleanedLines = new ArrayList<String>();
		String pendingSubject = null;
		for (String line : lines) {
			if (isGeneratedCommentLine(line) || isGeneratedTypeDeclaration(line)) {
				pendingSubject = subjectForInlineNamedIndividualType(line);
				continue;
			}
			if (pendingSubject != null) {
				if (line.trim().startsWith("<")) {
					cleanedLines.add(pendingSubject + " " + line.trim());
					pendingSubject = null;
					continue;
				}
				cleanedLines.add(pendingSubject);
				pendingSubject = null;
			}
			cleanedLines.add(line);
		}
		if (pendingSubject != null) {
			cleanedLines.add(pendingSubject);
		}
		Files.write(file.toPath(), cleanedLines, StandardCharsets.UTF_8);
	}
	
	private boolean isTurtleLike(File file) {
		String name = file.getName().toLowerCase();
		return name.endsWith(".ttl") || name.endsWith(".owl") || name.endsWith(".rdf");
	}
	
	private boolean containsOwlApiGeneratedComment(List<String> lines) {
		for (String line : lines) {
			if (line.contains(GENERATED_BY_OWLAPI)) {
				return true;
			}
		}
		return false;
	}
	
	private boolean isGeneratedCommentLine(String line) {
		String trimmed = line.trim();
		if (!trimmed.startsWith("#")) {
			return false;
		}
		String comment = trimmed.substring(1).trim();
		return comment.length() == 0
				|| comment.startsWith("#")
				|| comment.startsWith("###")
				|| comment.matches("#+")
				|| comment.equals("Classes")
				|| comment.equals("Object Properties")
				|| comment.equals("Data properties")
				|| comment.equals("Data Properties")
				|| comment.equals("Annotation properties")
				|| comment.equals("Annotation Properties")
				|| comment.equals("Individuals")
				|| comment.equals("Annotations")
				|| comment.startsWith(GENERATED_BY_OWLAPI)
				|| comment.matches("<?https?://[^\\s>]+>?")
				|| comment.matches("<?urn:[^\\s>]+>?");
	}
	
	private boolean isGeneratedTypeDeclaration(String line) {
		return isGeneratedObjectPropertyType(line) || isGeneratedNamedIndividualType(line);
	}
	
	private boolean isGeneratedObjectPropertyType(String line) {
		String subject = subjectIRI(line);
		return subject != null && objectPropertyIRIs.contains(subject) && isTypeLine(line, "ObjectProperty");
	}
	
	private boolean isGeneratedNamedIndividualType(String line) {
		String subject = subjectIRI(line);
		return subject != null && namedIndividualIRIs.contains(subject) && isTypeLine(line, "NamedIndividual");
	}
	
	private String subjectForInlineNamedIndividualType(String line) {
		if (isGeneratedNamedIndividualType(line) && line.trim().endsWith(";")) {
			String subject = subjectIRI(line);
			if (subject != null) {
				return "<" + subject + ">";
			}
		}
		return null;
	}
	
	private boolean isTypeLine(String line, String owlType) {
		return (line.contains("rdf:type") || line.matches(".*\\sa\\s+.*"))
				&& (line.contains("owl:" + owlType) || line.contains("http://www.w3.org/2002/07/owl#" + owlType));
	}
	
	private String subjectIRI(String line) {
		String trimmed = line.trim();
		if (!trimmed.startsWith("<")) {
			return null;
		}
		int end = trimmed.indexOf('>');
		if (end <= 1) {
			return null;
		}
		return trimmed.substring(1, end);
	}
}
